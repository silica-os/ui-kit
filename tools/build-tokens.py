#!/usr/bin/env python3
"""Build tokens/tokens.json, tokens/tokens.css and tokens/tokens.rs.

Inputs (tokens/): sketch-swatches-and-layer-styles.json and sketch-text-styles.json, exported from
the Sketch UI Kit with tools/export-tokens.js; static.json for what Sketch does not hold.
"""
import json
import math
import re
from pathlib import Path

T = Path(__file__).resolve().parents[1] / "tokens"
sw = json.loads((T / "sketch-swatches-and-layer-styles.json").read_text())
ts = json.loads((T / "sketch-text-styles.json").read_text())
static = json.loads((T / "static.json").read_text())

WEIGHT = {0: 100, 1: 200, 2: 300, 3: 300, 4: 400, 5: 400, 6: 500, 7: 500, 8: 600, 9: 700, 10: 800, 11: 900}


def hexa(c):
    c = c.upper()
    return c if len(c) == 9 else c + "FF"


colors = {"light": {}, "dark": {}}
brand = {}
for s in sw["swatches"]:
    mode, _, rest = s["name"].partition("/")
    if rest in ("Glass/Tint Thin", "Glass/Tint Thick"):
        continue  # retired: Amalfi has two glass materials, Regular and Clear (the swatches stay in the Sketch file, the API cannot delete them)
    if mode in ("Light", "Dark"):
        colors[mode.lower()][rest] = hexa(s["color"])
    elif mode == "Brand":
        brand[rest] = hexa(s["color"])

typography = {}
for s in ts:
    mode, style, role = s["name"].split("/", 2)
    t = typography.setdefault(style, {
        "family": s["family"], "size": s["size"], "lineHeight": s["lineHeight"],
        "weight": WEIGHT[s["weight"]], "sketchWeight": s["weight"], "colors": {"light": {}, "dark": {}}})
    t["colors"][mode.lower()][role] = hexa(s["color"])

glass = {}
for s in sw["styles"]:
    parts = s["name"].split("/")
    if parts[1] == "Glass":
        glass.setdefault(parts[2], {})[parts[0].lower()] = {
            k: s[k] for k in ("fills", "borders", "shadows", "innerShadows", "blurs") if s[k]}

tokens = {"$schema": "silica-amalfi-tokens/2", "name": "Silica 1.0 Amalfi",
          "source": "Silica 1.0 Amalfi UI Kit.sketch (DEB2F9E8-966A-4E25-A6AF-6BAF189DD87E): swatches, text styles, glass layer styles",
          "colors": colors, "brand": brand, "typography": typography, "glass": glass, **static}
(T / "tokens.json").write_text(json.dumps(tokens, indent=1) + "\n")


def lh(t):
    return f"{t['lineHeight']}px" if t["lineHeight"] else "normal"


def kebab(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def css_rgba(h):
    return f"#{h[1:]}" if h[7:] != "FF" else f"#{h[1:7]}"


def block(mode):
    return "".join(f"  --{kebab(k)}: {css_rgba(v)};\n" for k, v in colors[mode].items())


css = ["/* Generated by tools/build-tokens.py. Do not edit. */\n/* Light is the default; put data-theme=\"dark\" (or \"light\") on <html> or on any element to scope a theme. */\n:root, [data-theme='light'] {\n" + block("light")]
css.append("".join(f"  --brand-{kebab(k)}: {css_rgba(v)};\n" for k, v in brand.items()))
css.append("".join(f"  --space-{k}: {v}px;\n" for k, v in static["spacing"].items() if isinstance(v, (int, float))))
css.append("".join(f"  --control-{k}: {v}px;\n" for k, v in static["controlHeights"].items() if isinstance(v, (int, float))))
css.append("".join(f"  --radius-{kebab(k)}: {v}px;\n" for k, v in static["radii"].items() if isinstance(v, (int, float))))
for lvl, sh in static["shadows"]["light"].items():
    css.append(f"  --elevation-{lvl}: 0 {sh['y']}px {sh['blur']}px {css_rgba(sh['color'])};\n")
for name, f in static["motion"]["fades"].items():
    c = ", ".join(str(x) for x in f["curve"])
    css.append(f"  --fade-{name}: {f['duration']}ms cubic-bezier({c});\n")
for name, sp in static["motion"]["springs"].items():
    # springs as CSS: `transition: left var(--spring-snappy)` (duration, then a linear() easing sampled from the curve)
    r, z = sp["response"], sp["dampingRatio"]
    w = 2 * math.pi / r
    wd = w * math.sqrt(1 - z * z) if z < 1 else 0

    def prog(t):
        if t <= 0:
            return 0.0
        if z < 1:
            return 1 - math.exp(-z * w * t) * (math.cos(wd * t) + z * w / wd * math.sin(wd * t))
        return 1 - math.exp(-w * t) * (1 + w * t)

    settle = 0.0
    t = 0.0
    while t < 4:
        if abs(prog(t) - 1) > 0.005:
            settle = t
        t += 0.002
    dur = settle + 0.03
    pts = ",".join(f"{prog(i / 48 * dur):.4f}" for i in range(49))
    css.append(f"  --spring-{name}: {round(dur * 1000)}ms linear({pts});\n")
for name, t in typography.items():
    css.append(f"  --font-{kebab(name)}: {t['weight']} {t['size']}px/{lh(t)} '{t['family']}', system-ui, sans-serif;\n")
css.append("}\n\n[data-theme='dark'] {\n" + block("dark"))
for lvl, sh in static["shadows"]["dark"].items():
    css.append(f"  --elevation-{lvl}: 0 {sh['y']}px {sh['blur']}px {css_rgba(sh['color'])};\n")
css.append("}\n\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n"
           + block("dark").replace("  --", "    --")
           + "".join(f"    --elevation-{lvl}: 0 {sh['y']}px {sh['blur']}px {css_rgba(sh['color'])};\n" for lvl, sh in static["shadows"]["dark"].items())
           + "  }\n}\n")
(T / "tokens.css").write_text("".join(css))


def snake(s):
    return re.sub(r"[^A-Z0-9]+", "_", s.upper()).strip("_")


def rgba(h):
    return ", ".join(str(int(h[i:i + 2], 16)) for i in (1, 3, 5, 7))


rs = ["// Generated by tools/build-tokens.py. Do not edit.\n// Module of the same crate as rust/silica_motion.rs (`mod silica_motion; mod tokens;`).\n",
      "#![allow(dead_code)]\n\n",
      "#[derive(Clone, Copy, Debug, PartialEq)]\npub struct Rgba(pub u8, pub u8, pub u8, pub u8);\n\n",
      "#[derive(Clone, Copy, Debug)]\npub struct TextStyle {\n    pub family: &'static str,\n    pub size: f32,\n    pub line_height: f32, // 0.0 = font default\n    pub weight: u16,\n}\n\n"]
for mode in ("light", "dark"):
    rs.append(f"pub mod {mode} {{\n    use super::Rgba;\n")
    for k, v in colors[mode].items():
        rs.append(f"    pub const {snake(k)}: Rgba = Rgba({rgba(v)});\n")
    rs.append("}\n\n")
rs.append("pub mod brand {\n    use super::Rgba;\n")
for k, v in brand.items():
    rs.append(f"    pub const {snake(k)}: Rgba = Rgba({rgba(v)});\n")
rs.append("}\n\npub mod space {\n")
for k, v in static["spacing"].items():
    if isinstance(v, (int, float)):
        rs.append(f"    pub const {snake(k)}: f32 = {float(v)};\n")
rs.append("}\n\npub mod control {\n")
for k, v in static["controlHeights"].items():
    if isinstance(v, (int, float)):
        rs.append(f"    pub const {snake(k)}: f32 = {float(v)};\n")
rs.append("}\n\npub mod radius {\n")
for k, v in static["radii"].items():
    if isinstance(v, (int, float)):
        rs.append(f"    pub const {snake(k)}: f32 = {float(v)};\n")
rs.append("}\n\npub mod text {\n    use super::TextStyle;\n")
for k, t in typography.items():
    rs.append(f"    pub const {snake(k)}: TextStyle = TextStyle {{ family: \"{t['family']}\", size: {float(t['size'])}, line_height: {float(t['lineHeight'] or 0)}, weight: {t['weight']} }};\n")
rs.append("}\n\npub mod spring {\n    use crate::silica_motion::Spring;\n")
for k, s in static["motion"]["springs"].items():
    rs.append(f"    pub const {snake(k)}: Spring = Spring::new({s['response']}, {s['dampingRatio']});\n")
rs.append("}\n\npub mod fade {\n    use crate::silica_motion::Fade;\n")
for k, f in static["motion"]["fades"].items():
    rs.append(f"    pub const {snake(k)}: Fade = Fade {{ duration_ms: {f['duration']}, curve: {[float(x) for x in f['curve']]} }};\n".replace("'", ""))
rs.append("}\n")
(T / "tokens.rs").write_text("".join(rs))
print({"light": len(colors["light"]), "dark": len(colors["dark"]), "brand": len(brand),
       "typography": len(typography), "glass": list(glass)})
