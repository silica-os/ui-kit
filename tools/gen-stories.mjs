// Writes stories/components/<Category>.stories.js from kit/index.json: one story per component group
// (Category/Component) with Variant and Appearance controls, plus an "All variants" gallery story.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const { symbols } = JSON.parse(readFileSync(join(root, 'kit/index.json'), 'utf8'))
const out = join(root, 'stories/components')
rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })

const key = (s) => s.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : '')).replace(/^./, (c) => c.toUpperCase())

const byCategory = new Map()
for (const s of symbols) {
  const p = s.name.split('/')
  const group = p.length > 2 ? p.slice(0, 2).join('/') : s.name
  const rest = p.length > 2 ? p.slice(2) : []
  const appearance = ['Light', 'Dark'].includes(rest[rest.length - 1]) ? rest.pop() : '-'
  const cat = byCategory.get(s.category) || new Map()
  const g = cat.get(group) || { variants: {}, appearances: new Set() }
  g.variants[rest.join(' / ') || '-'] ||= {}
  g.variants[rest.join(' / ') || '-'][appearance] = s.name
  g.appearances.add(appearance)
  cat.set(group, g)
  byCategory.set(s.category, cat)
}

let files = 0
for (const [category, groups] of byCategory) {
  const lines = [
    `// Generated by tools/gen-stories.mjs from kit/index.json. Do not edit.`,
    `import KitSymbol from '../../src/render/KitSymbol.vue'`,
    `import KitGallery from '../../src/render/KitGallery.vue'`,
    ``,
    `export default { title: 'Components/${category}', parameters: { layout: 'padded' } }`,
    ``,
    `const pick = (variants, variant, appearance) => {`,
    `  const v = variants[variant] || Object.values(variants)[0]`,
    `  return v[appearance] || Object.values(v)[0]`,
    `}`,
    ``,
  ]
  for (const [group, g] of groups) {
    const variants = Object.keys(g.variants).sort()
    const appearances = [...g.appearances].sort((a, b) => (a === 'Light' ? -1 : b === 'Light' ? 1 : a.localeCompare(b)))
    const id = key(group.split('/').slice(1).join(' ') || group)
    const data = JSON.stringify(g.variants)
    lines.push(
      `const ${id}Variants = ${data}`,
      `export const ${id} = {`,
      `  name: ${JSON.stringify(group.split('/').slice(1).join(' / ') || group)},`,
      `  args: { variant: ${JSON.stringify(variants[0])}, appearance: ${JSON.stringify(appearances[0])}, scale: 1 },`,
      `  argTypes: {`,
      `    variant: { control: 'select', options: ${JSON.stringify(variants)} },`,
      `    appearance: { control: 'inline-radio', options: ${JSON.stringify(appearances)} },`,
      `    scale: { control: { type: 'range', min: 0.5, max: 3, step: 0.25 } },`,
      `  },`,
      `  render: (args) => ({`,
      `    components: { KitSymbol },`,
      `    setup: () => ({ args, name: () => pick(${id}Variants, args.variant, args.appearance) }),`,
      `    template: '<KitSymbol :name="name()" :scale="args.scale" />',`,
      `  }),`,
      `}`,
      `export const ${id}All = {`,
      `  name: ${JSON.stringify((group.split('/').slice(1).join(' / ') || group) + ' · all variants')},`,
      `  args: { appearance: ${JSON.stringify(appearances[0])}, scale: 1 },`,
      `  argTypes: {`,
      `    appearance: { control: 'inline-radio', options: ${JSON.stringify(appearances)} },`,
      `    scale: { control: { type: 'range', min: 0.5, max: 3, step: 0.25 } },`,
      `  },`,
      `  render: (args) => ({`,
      `    components: { KitGallery },`,
      `    setup: () => ({ args, names: () => Object.values(${id}Variants).map((v) => v[args.appearance] || Object.values(v)[0]) }),`,
      `    template: '<KitGallery :names="names()" :scale="args.scale" />',`,
      `  }),`,
      `}`,
      ``,
    )
  }
  writeFileSync(join(out, `${key(category)}.stories.js`), lines.join('\n'))
  files++
}
console.log(files, 'story files')
