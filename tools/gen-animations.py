#!/usr/bin/env python3
"""Generate rust/animations.rs from animations/*.json (files saved from the Animation Lab)."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROP = {"x": "TranslateX", "y": "TranslateY", "scale": "Scale", "rotate": "Rotate", "opacity": "Opacity"}


def snake(s):
    return re.sub(r"[^A-Z0-9]+", "_", s.upper()).strip("_")


def driver(d):
    if d["type"] == "spring":
        if d.get("preset"):
            return f"Driver::Spring(spring::{snake(d['preset'].split('.', 1)[1])})"
        return f"Driver::Spring(Spring::new({d['response']}, {d['dampingRatio']}))"
    if d.get("preset"):
        return f"Driver::Fade(fade::{snake(d['preset'].split('.', 1)[1])})"
    return f"Driver::Bezier {{ duration_ms: {d['durationMs']}, curve: {[float(x) for x in d['curve']]} }}"


out = ["// Generated by tools/gen-animations.py from animations/*.json. Do not edit.\n",
       "#![allow(dead_code)]\n\n",
       "use crate::silica_motion::{Animation, Driver, Prop, Spring, Track};\n",
       "use crate::tokens::{fade, spring};\n\n"]
names = []
for f in sorted((ROOT / "animations").glob("*.json")):
    a = json.loads(f.read_text())
    n = snake(a["name"])
    names.append((n, a))
    out.append(f"/// Target: {a.get('target') or 'any'}\n" + (f"/// {a['description']}\n" if a.get("description") else ""))
    out.append(f"pub const {n}: Animation = Animation {{\n    name: \"{a['name']}\",\n    delay_ms: {a.get('delayMs', 0)},\n    driver: {driver(a['driver'])},\n    tracks: &[\n")
    for t in a["tracks"]:
        out.append(f"        Track {{ prop: Prop::{PROP[t['prop']]}, from: {float(t['from'])}, to: {float(t['to'])} }},\n")
    out.append("    ],\n};\n\n")
out.append("pub const ALL: &[&Animation] = &[" + ", ".join(f"&{n}" for n, _ in names) + "];\n")
(ROOT / "rust" / "animations.rs").write_text("".join(out))
print(len(names), "animations")
